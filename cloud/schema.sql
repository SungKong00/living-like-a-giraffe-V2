CREATE TABLE IF NOT EXISTS world (id INTEGER PRIMARY KEY CHECK (id=1), version INTEGER NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings (name TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (digest TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS files (name TEXT NOT NULL, part INTEGER NOT NULL, content TEXT NOT NULL, PRIMARY KEY(name,part)) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS draft_versions (
  id TEXT PRIMARY KEY, kind TEXT NOT NULL, title TEXT NOT NULL, createdAt TEXT NOT NULL,
  revision TEXT NOT NULL, model TEXT NOT NULL, layout TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS draft_versions_model ON draft_versions(model);
CREATE INDEX IF NOT EXISTS draft_versions_time ON draft_versions(createdAt DESC);
